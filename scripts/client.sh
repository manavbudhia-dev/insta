#!/usr/bin/env bash
# One command per client: a separate DM Autopilot for each client on its own subdomain.
#
#   scripts/client.sh add <name> <instagram_username> [email]   # e.g. add kalyanakuri kalyanakuri.in owner@gmail.com
#                                                    #  ->  https://kalyanakuri.zealcoder.in (email = Google / email-link login)
#   scripts/client.sh list
#   scripts/client.sh password <name>
#   scripts/client.sh remove <name> [--purge]            # --purge also deletes the client's data volume
#   scripts/client.sh sync                               # rebuild generated files and restart everything
#
# Run it on the server, in the app folder (next to docker-compose.yml and .env). Each client gets its own container,
# its own SQLite data volume, its own login, and HTTPS from Caddy. Instagram webhooks keep arriving at the main
# instance (Meta allows one callback URL per app), which passes them on; each client only acts on its own account.
#
# Once, before the first client: point a wildcard DNS record  *.<root domain>  (A record) at this server.
# Options: --no-start (only write files; used by tests).
set -euo pipefail
cd "$(dirname "$0")/.."

CLIENTS_DIR="${CLIENTS_DIR:-clients}"
SHARED="$CLIENTS_DIR/shared"
COMPOSE_CLIENTS="${COMPOSE_CLIENTS:-docker-compose.clients.yml}"
RESERVED="insta www app api n8n mail admin shared"

die() { echo "error: $*" >&2; exit 1; }
envget() { # envget FILE KEY
  [ -f "$1" ] || return 0
  grep -E "^$2=" "$1" | tail -1 | cut -d= -f2- | sed -e 's/^"//' -e 's/"$//' || true
}
rand() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c "$1" || true; }
envset() { # envset FILE KEY VALUE  (empty VALUE removes the key)
  local tmp="$1.tmp.$$"
  awk -v k="$2" -v v="$3" 'BEGIN{done=0} $0 ~ "^"k"=" { if (v != "" && !done) { print k"="v; done=1 } next } { print } END{ if (v != "" && !done) print k"="v }' "$1" >"$tmp"
  chmod 600 "$tmp"; mv "$tmp" "$1"
}

[ -f .env ] || die "run this in the app folder on the server (no .env here)"
MAIN_URL="$(envget .env BASE_URL)"; MAIN_URL="${MAIN_URL%/}"
[ -n "$MAIN_URL" ] || die "BASE_URL is not set in .env"
MAIN_HOST="${MAIN_URL#*://}"; MAIN_HOST="${MAIN_HOST%%/*}"
ROOT_DOMAIN="$(envget .env CLIENT_ROOT_DOMAIN)"
[ -n "$ROOT_DOMAIN" ] || ROOT_DOMAIN="${MAIN_HOST#*.}"   # insta.zealcoder.in -> zealcoder.in

NO_START=0
ARGS=()
for a in "$@"; do case "$a" in --no-start) NO_START=1 ;; *) ARGS+=("$a") ;; esac; done
set -- "${ARGS[@]+"${ARGS[@]}"}"

dc() {
  local files=(-f docker-compose.yml)
  [ -f "$COMPOSE_CLIENTS" ] && files+=(-f "$COMPOSE_CLIENTS")
  if docker compose version >/dev/null 2>&1; then docker compose "${files[@]}" "$@"; else docker-compose "${files[@]}" "$@"; fi
}

clients() { # names of configured clients
  [ -d "$CLIENTS_DIR" ] || return 0
  for f in "$CLIENTS_DIR"/*/.env; do [ -f "$f" ] && basename "$(dirname "$f")"; done | grep -v '^shared$' || true
}

generate() {
  mkdir -p "$SHARED/caddy"
  local names; names="$(clients)"
  # Every client needs a control key so the main dashboard's Clients page can switch its tools (older clients get one here).
  # Shared settings follow the main .env: email (Resend), where unlock requests go, and Google sign-in through the main site.
  local via=""; [ -n "$(envget .env GOOGLE_CLIENT_ID)" ] && via="$MAIN_URL"
  for n in $names; do
    if [ -z "$(envget "$CLIENTS_DIR/$n/.env" CONTROL_SECRET)" ]; then printf 'CONTROL_SECRET=%s\n' "$(rand 48)" >>"$CLIENTS_DIR/$n/.env"; fi
    for k in RESEND_API_KEY EMAIL_FROM OWNER_EMAIL; do envset "$CLIENTS_DIR/$n/.env" "$k" "$(envget .env "$k")"; done
    envset "$CLIENTS_DIR/$n/.env" GOOGLE_AUTH_VIA "$via"
  done
  local tmp="$COMPOSE_CLIENTS.tmp"
  {
    echo "# Generated by scripts/client.sh - do not edit by hand."
    echo "services:"
    if [ -z "$names" ]; then echo "  {}"; fi
    for n in $names; do cat <<EOF
  client-$n:
    image: insta-app:latest
    restart: unless-stopped
    env_file: $CLIENTS_DIR/$n/.env
    environment:
      DATA_DIR: /data
    volumes:
      - client-$n-data:/data
    expose:
      - "3000"
    read_only: true
    tmpfs:
      - /tmp
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL
    cap_add: [CHOWN, SETUID, SETGID, DAC_OVERRIDE, FOWNER]
    pids_limit: 256
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:3000/healthz').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"]
      interval: 30s
      timeout: 5s
      retries: 3
EOF
    done
    if [ -n "$names" ]; then
      echo "volumes:"
      for n in $names; do echo "  client-$n-data:"; done
    fi
  } >"$tmp"
  mv "$tmp" "$COMPOSE_CLIENTS"

  # Caddy: one site per client (HTTPS certificate fetched automatically once DNS points here).
  find "$SHARED/caddy" -name 'client-*.caddy' -delete
  for n in $names; do
    cat >"$SHARED/caddy/client-$n.caddy" <<EOF
$n.$ROOT_DOMAIN {
	encode gzip
	header -Server
	request_body {
		max_size 400MB
	}
	# The owner's control API is only for the private Docker network.
	respond /internal/* 404
	reverse_proxy client-$n:3000
}
EOF
  done

  # The main dashboard's Clients page: where each client lives inside the Docker network, and its control key.
  local cj="[" csep=""
  for n in $names; do
    cj="$cj$csep{\"name\":\"$n\",\"url\":\"https://$n.$ROOT_DOMAIN\",\"internal\":\"http://client-$n:3000\",\"ig\":\"$(envget "$CLIENTS_DIR/$n/.env" IG_ACCOUNT_LOCK | tr -cd 'A-Za-z0-9._,-')\",\"secret\":\"$(envget "$CLIENTS_DIR/$n/.env" CONTROL_SECRET | tr -cd 'A-Za-z0-9')\"}"
    csep=","
  done
  ( umask 022; printf '%s]\n' "$cj" >"$SHARED/clients.json.tmp" )
  mv "$SHARED/clients.json.tmp" "$SHARED/clients.json"

  # The main instance passes Meta's webhooks on to these.
  local json="[" sep=""
  for n in $names; do json="$json$sep\"http://client-$n:3000\""; sep=","; done
  printf '%s]\n' "$json" >"$SHARED/forward.json.tmp"
  mv "$SHARED/forward.json.tmp" "$SHARED/forward.json"
}

reload_caddy() {
  dc exec -T caddy caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null \
    || dc restart caddy
}

cmd="${1:-}"
case "$cmd" in
  add)
    name="${2:-}"; ig="${3:-}"; ig="${ig#@}"; email="$(printf '%s' "${4:-}" | tr 'A-Z' 'a-z')"
    if [ -n "$email" ] && ! [[ "$email" =~ ^[^[:space:]@,]+@[^[:space:]@,]+\.[a-z]{2,}$ ]]; then die "\"$email\" is not an email address"; fi
    [[ "$name" =~ ^[a-z0-9][a-z0-9-]{1,30}$ ]] || die "name must be 2-31 characters: a-z, 0-9 and -, e.g. kalyanakuri"
    for r in $RESERVED; do [ "$name" = "$r" ] && die "\"$name\" is reserved, pick another name"; done
    [ -n "$ig" ] || die "usage: scripts/client.sh add <name> <instagram_username>"
    [ -f "$CLIENTS_DIR/$name/.env" ] && die "client \"$name\" already exists (scripts/client.sh password $name)"
    mkdir -p "$CLIENTS_DIR/$name"
    pw="$(rand 20)"
    ( umask 077; cat >"$CLIENTS_DIR/$name/.env" <<EOF
# Client: $name (Instagram @$ig), created $(date -u +%Y-%m-%d)
CLIENT_NAME=$name
BASE_URL=https://$name.$ROOT_DOMAIN
ADMIN_PASSWORD=$pw
SESSION_SECRET=$(rand 48)
IG_ACCOUNT_LOCK=$ig
WEBHOOK_CALLBACK_URL=$MAIN_URL/webhook
WEBHOOK_VERIFY_TOKEN=$(envget .env WEBHOOK_VERIFY_TOKEN)
META_APP_ID=$(envget .env META_APP_ID)
META_APP_SECRET=$(envget .env META_APP_SECRET)
META_CONFIG_ID=$(envget .env META_CONFIG_ID)
GRAPH_VERSION=$(envget .env GRAPH_VERSION)
CONTROL_SECRET=$(rand 48)
LOGIN_EMAILS=$email
EOF
    # LinkedIn app and AI key: the client's LinkedIn scheduler uses yours unless they set their own in its Settings.
    for k in LINKEDIN_CLIENT_ID LINKEDIN_CLIENT_SECRET LINKEDIN_VERSION ANTHROPIC_API_KEY; do
      v="$(envget .env "$k")"; if [ -n "$v" ]; then printf '%s=%s\n' "$k" "$v" >>"$CLIENTS_DIR/$name/.env"; fi
    done
    )
    generate
    if [ "$NO_START" = 0 ]; then
      docker image inspect insta-app:latest >/dev/null 2>&1 || dc build app
      dc up -d app "client-$name"   # app restarts only if its config changed
      reload_caddy
    fi
    cat <<EOF

Client "$name" is ready.
  Dashboard : https://$name.$ROOT_DOMAIN
  Password  : $pw
  Instagram : @$ig (only this account can be connected here)
  Tools     : all on. Switch them per client on $MAIN_URL/clients
  Login     : ${email:-password only}$([ -n "$email" ] && echo ' (Google or email link; send the welcome email from the Clients page)')

Next:
  1. Client: Meta Business Settings -> Partners -> share the Instagram account @$ig with your business portfolio,
     and turn on "Allow access to messages" in the Instagram app.
  2. You: assign @$ig to your system user, open the dashboard above, Connect with Instagram (or paste the
     system user token on Overview). Webhooks need no change in Meta.
  3. If you use "Connect with Instagram", add https://$name.$ROOT_DOMAIN/auth/instagram/callback to the
     Meta app's Valid OAuth Redirect URIs once.
  4. LinkedIn: add https://$name.$ROOT_DOMAIN/linkedin/auth/linkedin/callback to your LinkedIn app's redirect URLs.
     WhatsApp: the client's number must be in your Meta app; its webhooks are passed on like Instagram's.
EOF
    ;;
  remove)
    name="${2:-}"
    [ -f "$CLIENTS_DIR/$name/.env" ] || die "no client \"$name\""
    purge=0; [ "${3:-}" = "--purge" ] && purge=1
    if [ "$NO_START" = 0 ]; then
      dc rm -sf "client-$name" >/dev/null || true
    fi
    rm -rf "${CLIENTS_DIR:?}/$name"
    generate
    if [ "$NO_START" = 0 ]; then
      if [ "$purge" = 1 ]; then
        proj="$(basename "$PWD" | tr -cd 'a-z0-9_-')"
        docker volume rm "${COMPOSE_PROJECT_NAME:-$proj}_client-$name-data" >/dev/null 2>&1 || echo "note: data volume not found or in use"
      fi
      reload_caddy
    fi
    echo "Client \"$name\" removed.$([ "$purge" = 1 ] && echo ' Its data was deleted.' || echo ' Its data volume was kept (add --purge to delete it).')"
    ;;
  list)
    names="$(clients)"
    [ -n "$names" ] || { echo "No clients yet. Add one: scripts/client.sh add <name> <instagram_username>"; exit 0; }
    for n in $names; do
      printf '%-20s https://%s.%s   @%s\n' "$n" "$n" "$ROOT_DOMAIN" "$(envget "$CLIENTS_DIR/$n/.env" IG_ACCOUNT_LOCK)"
    done
    ;;
  password)
    name="${2:-}"
    [ -f "$CLIENTS_DIR/$name/.env" ] || die "no client \"$name\""
    envget "$CLIENTS_DIR/$name/.env" ADMIN_PASSWORD
    ;;
  sync)
    generate
    if [ "$NO_START" = 0 ]; then dc up -d --remove-orphans; reload_caddy; fi
    echo "Synced $(clients | wc -w | tr -d ' ') client(s)."
    ;;
  *)
    sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'
    exit 1
    ;;
esac
