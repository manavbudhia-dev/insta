function auth(req, res, next) {
  if (isOwner(req)) { const o = ownerUser(); if (o) { req.user = o; req.owner = true; return next(); } }
  try {
    const t = jwt.verify(req.cookies[COOKIE], SESSION_SECRET);
    const u = db.prepare('select id,email,name,role,created_at from users where id=?').get(t.id);
    if (!u) throw new Error();
    // SQLite hands a deleted user's id to the next person added. A cookie issued before this account existed is not theirs.
    if (u.created_at && t.iat && t.iat * 1000 < u.created_at - 2000) throw new Error();
    delete u.created_at;
    req.user = u; next();
  } catch { res.status(401).json({ error: 'Sign in required' }); }
}
