function ownPost(req, res) {
  const p = db.prepare('select * from posts where id=?').get(req.params.id);
  if (!p) { res.status(404).json({ error: 'Not found' }); return null; }
  if (p.created_by !== req.user.id && req.user.role !== 'admin') { res.status(403).json({ error: 'Only the author or an admin can do that' }); return null; }
  return p;
}
app.delete('/api/posts/:id', auth, (req, res) => {
  const p = ownPost(req, res); if (!p) return;
  if (p.status === 'publishing') return res.status(409).json({ error: 'Publishing right now' });
  deleteMedia(mediaIds(p)); db.prepare('delete from posts where id=?').run(p.id); res.json({ ok: true });
});
app.post('/api/posts/:id/retry', auth, wrap(async (req, res) => {
  const p = ownPost(req, res); if (!p) return;
  if (!['failed', 'scheduled'].includes(p.status)) return res.status(409).json({ error: 'Only failed or scheduled posts can be sent now' });
  const r = db.prepare("update posts set status='scheduled', when_at=?, attempts=0, error=null where id=? and status in ('failed','scheduled')").run(Date.now(), p.id);
  if (!r.changes) return res.status(409).json({ error: 'Publishing right now' });
  publishDue().catch((e) => console.error('Publishing:', e.message));
  res.json({ ok: true });
}));

app.put('/api/posts/:id', auth, (req, res) => {
  const p = ownPost(req, res); if (!p) return;
  if (!['draft', 'scheduled', 'failed'].includes(p.status)) return res.status(409).json({ error: p.status === 'publishing' ? 'Publishing right now' : 'Published posts can’t be edited' });
  const r = parsePost(req, { draft: !!req.body.draft && p.status === 'draft', post: p });
  if (r.error) return res.status(400).json({ error: r.error });
  const { f, ids } = r;
  const gone = mediaIds(p).filter((id) => !ids.includes(id));
  const ok = db.transaction(() => {
    const cur = db.prepare('select status from posts where id=?').get(p.id);
    if (!cur || !['draft', 'scheduled', 'failed'].includes(cur.status)) return false; // the scheduler claimed it meanwhile
    db.prepare('update posts set account_id=?, text=?, when_at=?, status=?, attempts=0, error=null, type=?, media_json=?, poll_json=?, updated_at=? where id=?')
      .run(f.accountId, f.body, f.whenAt, f.status, f.type, f.mediaJson, f.pollJson, Date.now(), p.id);
    for (const m of ids) db.prepare('update media set post_id=? where id=?').run(p.id, m);
    return true;
  })();
  if (!ok) return res.status(409).json({ error: 'Publishing right now' });
  deleteMedia(gone);
  res.json({ id: p.id, status: f.status });
});
