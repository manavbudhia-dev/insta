/* ---- Session ---- */
const tries = new Map(), setupTries = new Map(), DUMMY_HASH = bcrypt.hashSync(randomBytes(8).toString('hex'), 12);
setInterval(() => { const cut = Date.now() - 15 * 60e3; for (const [k, v] of tries) if (v.at < cut) tries.delete(k); for (const [k, v] of setupTries) if (v.at < cut) setupTries.delete(k); }, 5 * 60e3).unref();
app.post('/api/login', (req, res) => {
  const k = req.ip, t = tries.get(k) || { n: 0, at: Date.now() };
  if (Date.now() - t.at > 15 * 60e3) { t.n = 0; t.at = Date.now(); }
  if (t.n >= 15) return res.status(429).json({ error: 'Too many attempts. Try again in 15 minutes.' });
  const u = db.prepare('select * from users where email=?').get(String(req.body.email || '').trim().toLowerCase());
  const okPw = bcrypt.compareSync(String(req.body.password || ''), u ? u.hash : DUMMY_HASH); // same work whether or not the email exists
  if (!u || !okPw) { t.n++; tries.set(k, t); return res.status(401).json({ error: 'Wrong email or password' }); }
  res.cookie(COOKIE, jwt.sign({ id: u.id }, SESSION_SECRET, { expiresIn: '7d' }), cookieOpts(req));
  res.json({ id: u.id, email: u.email, name: u.name, role: u.role });
});
