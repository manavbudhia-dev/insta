/* Webhook for n8n, Zapier, Make or a script: POST posts in, they land in your empty slots.
   Send the token as "Authorization: Bearer <token>" or "X-Autopilot-Token". No cookie needed.
   Body: {"text":"..."} or {"posts":["...", {"text":"...","when":"2026-11-02T10:00:00+05:30"}]}
   Add "split":true to cut one long text into posts at lines containing only ---. */
const hits = [], badTokens = new Map(); // flood guard: 60 good calls a minute, 10 wrong tokens a minute per address
setInterval(() => { const cut = Date.now() - 60_000; for (const [k, v] of badTokens) if (v.at < cut) badTokens.delete(k); }, 60_000).unref();
app.post('/api/inbound', (req, res) => {
  const now = Date.now(), bad = badTokens.get(req.ip) || { n: 0, at: now };
  if (now - bad.at > 60_000) { bad.n = 0; bad.at = now; }
  if (bad.n >= 10) return res.status(429).json({ error: 'Too many requests' });
  const tok = (req.get('authorization') || '').replace(/^Bearer\s+/i, '') || req.get('x-autopilot-token') || '';
  if (!auto.checkInboundToken(tok)) { bad.n++; badTokens.set(req.ip, bad); return res.status(401).json({ error: 'Invalid or missing token' }); }
  while (hits.length && hits[0] < now - 60_000) hits.shift();
  if (hits.length >= 60) return res.status(429).json({ error: 'Too many requests' });
  hits.push(now);
  try {
    const b = req.body || {};
    let items = Array.isArray(b.posts) ? b.posts.map((p) => (typeof p === 'string' ? { text: p } : { text: p?.text, when: p?.when }))
      : b.text != null ? (b.split ? auto.splitPosts(b.text).map((text) => ({ text })) : [{ text: b.text, when: b.when }]) : [];
    items = items.slice(0, 20);
    if (!items.length) return res.status(400).json({ error: 'Send {"text":"..."} or {"posts":[...]}' });
    const r = auto.addPosts(items, { status: auto.getConfig().inboundMode === 'schedule' ? 'scheduled' : 'draft' });
    res.status(r.created ? 201 : 200).json(r);
  } catch (e) { res.status(e.status || 500).json({ error: e.message }); }
});

