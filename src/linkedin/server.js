const DURATIONS = ['ONE_DAY', 'THREE_DAYS', 'SEVEN_DAYS', 'FOURTEEN_DAYS'];

// Validates a post payload for both create and edit. Returns { error } or { f, ids }.
// Drafts are saved loosely (no time, media or poll rules) so work in progress is never rejected.
function parsePost(req, { draft, post }) {
  const { accountId, text, whenAt } = req.body;
  const type = ['text', 'image', 'video', 'poll'].includes(req.body.type) ? req.body.type : 'text';
  const body = String(text || '').trim();
  const bad = (error) => ({ error });
  if (!body || body.length > 3000) return bad('Post text must be 1 to 3000 characters');
  if (!db.prepare('select 1 from accounts where id=?').get(accountId)) return bad('Choose an account to post as');
  if (!draft && (!Number.isFinite(+whenAt) || +whenAt < Date.now() - 60_000)) return bad('Pick a time in the future');

  let mediaJson = null, pollJson = null, ids = [];
  if (type === 'image' || type === 'video') {
    const items = Array.isArray(req.body.media) ? req.body.media : [];
    const max = type === 'video' ? 1 : 9;
    if (items.length > max || (!draft && items.length < 1)) return bad(type === 'video' ? 'Add one video' : 'Add 1 to 9 images');
    ids = items.map((i) => +i.id);
    if (new Set(ids).size !== ids.length) return bad('The same file was added twice');
    const rows = ids.map((id) => db.prepare('select * from media where id=?').get(id));
    if (rows.some((m) => !m || (m.post_id && m.post_id !== post?.id) || m.kind !== type || (m.created_by !== req.user.id && req.user.role !== 'admin')))
      return bad('A file is missing or already used. Upload it again.');
    // Keep the LinkedIn URN of files already uploaded for this same account, so a retry doesn't upload them twice.
    let before = []; try { before = post && post.account_id === +accountId ? JSON.parse(post.media_json || '[]') : []; } catch { /* ignore */ }
    mediaJson = JSON.stringify(items.map((i) => {
      const prev = before.find((b) => b.id === +i.id);
      return { id: +i.id, label: String(i.alt || '').trim().slice(0, type === 'video' ? 200 : 1000), ...(prev?.urn ? { urn: prev.urn } : {}) };
    }));
  } else if (type === 'poll') {
    const p = req.body.poll || {};
    const question = String(p.question || '').trim();
    const options = (Array.isArray(p.options) ? p.options : []).map((o) => String(o || '').trim()).filter(Boolean);
    const duration = DURATIONS.includes(p.duration) ? p.duration : (draft ? 'THREE_DAYS' : null);
    if (question.length > 140 || (!draft && !question)) return bad('Poll question must be 1 to 140 characters');
    if (options.length > 4 || options.some((o) => o.length > 30) || (!draft && options.length < 2)) return bad('A poll needs 2 to 4 options of up to 30 characters each');
    if (!duration) return bad('Choose how long the poll stays open');
    pollJson = JSON.stringify({ question, options, duration });
  }
  const now = Date.now();
  return { ids, f: { accountId: +accountId, body, type, mediaJson, pollJson, whenAt: draft ? now : +whenAt, status: draft ? 'draft' : 'scheduled' } };
}

app.post('/api/posts', auth, (req, res) => {
  const r = parsePost(req, { draft: !!req.body.draft });
  if (r.error) return res.status(400).json({ error: r.error });
  const { f, ids } = r, now = Date.now();
  const id = db.transaction(() => {
    const ins = db.prepare('insert into posts(account_id,text,when_at,status,created_by,created_at,updated_at,type,media_json,poll_json) values(?,?,?,?,?,?,?,?,?,?)')
      .run(f.accountId, f.body, f.whenAt, f.status, req.user.id, now, now, f.type, f.mediaJson, f.pollJson);
    for (const m of ids) db.prepare('update media set post_id=? where id=?').run(ins.lastInsertRowid, m);
    return ins.lastInsertRowid;
  })();
  res.json({ id, status: f.status });
});

/* ---- Media uploads (streamed straight to disk, so large videos don't sit in memory) ---- */
const MB = 1048576;
const LIMITS = { image: (+process.env.MAX_IMAGE_MB || 10) * MB, video: (+process.env.MAX_VIDEO_MB || 200) * MB };
const TYPES = { 'image/jpeg': ['image', 'jpg'], 'image/png': ['image', 'png'], 'image/gif': ['image', 'gif'], 'video/mp4': ['video', 'mp4'] };
const looksRight = (b, mime) =>
  mime === 'image/jpeg' ? b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff
  : mime === 'image/png' ? b.subarray(0, 4).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47]))
  : mime === 'image/gif' ? b.subarray(0, 3).toString() === 'GIF'
  : b.subarray(4, 8).toString() === 'ftyp';

app.post('/api/media', auth, (req, res) => {
  const mime = String(req.headers['content-type'] || '').split(';')[0].trim().toLowerCase();
  const t = TYPES[mime];
  if (!t) return res.status(415).json({ error: 'Use a JPG, PNG, GIF or MP4 file' });
  const [kind, ext] = t, max = LIMITS[kind];
  const tooBig = `That file is too large. ${kind === 'video' ? 'Videos' : 'Images'} can be up to ${max / MB} MB.`;
  if (+req.headers['content-length'] > max) return res.status(413).set('Connection', 'close').json({ error: tooBig });

  let name = 'upload';
  try { name = decodeURIComponent(String(req.headers['x-filename'] || 'upload')).slice(0, 120); } catch { /* keep default */ }
  const file = `${randomBytes(16).toString('hex')}.${ext}`, full = path.join(MEDIA_DIR, file);
  const out = fs.createWriteStream(full);
  let size = 0, done = false;
  const drop = () => { done = true; req.unpipe(out); out.destroy(); fs.rm(full, { force: true }, () => {}); };
  const fail = (code, msg) => { if (done) return; drop(); res.status(code).set('Connection', 'close').json({ error: msg }); };

  req.on('data', (c) => { size += c.length; if (size > max) fail(413, tooBig); });
  req.on('error', () => fail(400, 'Upload was interrupted'));
  req.on('close', () => { if (!req.complete && !done) drop(); });
  out.on('error', () => fail(500, 'Could not save the file'));
  out.on('finish', () => {
    if (done) return;
    try {
      const head = Buffer.alloc(12), fd = fs.openSync(full, 'r');
      try { fs.readSync(fd, head, 0, 12, 0); } finally { fs.closeSync(fd); }
      if (!looksRight(head, mime)) return fail(400, `That doesn't look like a real ${mime.split('/')[1].toUpperCase()} file`);
      if (kind === 'video' && size < 75 * 1024) return fail(400, 'LinkedIn needs videos of at least 75 KB');
      const r = db.prepare('insert into media(file,kind,mime,name,size,created_by,created_at) values(?,?,?,?,?,?,?)')
        .run(file, kind, mime, name, size, req.user.id, Date.now());
      done = true;
      res.json({ id: r.lastInsertRowid, kind, name, size });
    } catch (e) { console.error('Upload failed:', e.message); fail(500, 'Could not save the file'); }
  });
  req.pipe(out);
});
